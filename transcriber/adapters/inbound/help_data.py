"""Build the rubric data of the help page (``web/js/lib/help-rubric.js``).

``python -m transcriber.adapters.inbound.help_data`` reads the rubric
files (``knowledge/rubrics/core.es.json`` and ``core.en.json``) and
writes the one JavaScript module the page ``#/help/analysis`` draws
the competencies from, so the web holds no definition of its own: what
a competency is, how a positive and a negative behaviour sound, where
it helps and what it does not look at all come from the rubric.
``--check`` exits with 1 when the committed module is out of date.
"""

import argparse
import json
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence

ROOT = Path(__file__).resolve().parents[3]
RUBRICS = ROOT / "knowledge" / "rubrics"
OUT = Path(__file__).resolve().parent / "web" / "js" / "lib" / "help-rubric.js"
LANGUAGES = ("es", "en")
HEADER = (
    "// The rubric as the help page draws it. Generated by\n"
    "// `python -m transcriber.adapters.inbound.help_data` from\n"
    "// knowledge/rubrics/core.<lang>.json: do not edit by hand.\n\n"
)


def first_positive_example(competency: Dict[str, Any]) -> str:
    """Return the first example sentence of a positive indicator."""
    for indicator in competency["indicators"]:
        if indicator["polarity"] == "positive" and indicator["examples"]:
            return str(indicator["examples"][0])
    return ""


def first_negative(competency: Dict[str, Any]) -> str:
    """Return the text of the first negative indicator."""
    for indicator in competency["indicators"]:
        if indicator["polarity"] == "negative":
            return str(indicator["text"])
    return ""


def competency_entry(competency: Dict[str, Any]) -> Dict[str, Any]:
    """Return what the help page shows of one competency."""
    practice = competency.get("practice", {})
    return {
        "id": competency["id"],
        "name": competency["name"],
        "definition": competency["definition"],
        "positive": first_positive_example(competency),
        "negative": first_negative(competency),
        "helps": list(practice.get("helps", [])),
        "hurts": list(practice.get("hurts", [])),
        "limits": competency["limits"],
    }


def build_rubric(rubrics: Path = RUBRICS) -> Dict[str, List[Dict[str, Any]]]:
    """Return ``{language: [competency entries]}`` from the rubric files."""
    out: Dict[str, List[Dict[str, Any]]] = {}
    for language in LANGUAGES:
        path = rubrics / f"core.{language}.json"
        rubric = json.loads(path.read_text(encoding="utf-8"))
        out[language] = [
            competency_entry(c) for c in rubric["competencies"]
        ]
    return out


def render(rubric: Dict[str, List[Dict[str, Any]]]) -> str:
    """Return the text of the JavaScript module."""
    body = json.dumps(rubric, ensure_ascii=False, indent=2)
    return f"{HEADER}export const HELP_RUBRIC = {body};\n"


def main(argv: Optional[Sequence[str]] = None) -> int:
    """Write (or with ``--check`` verify) the module; return the exit code."""
    parser = argparse.ArgumentParser(
        prog="python -m transcriber.adapters.inbound.help_data",
        description="Build the help page's rubric module.",
    )
    parser.add_argument("--rubrics", type=Path, default=RUBRICS)
    parser.add_argument("--out", type=Path, default=OUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    text = render(build_rubric(args.rubrics))
    if args.check:
        current = (
            args.out.read_text(encoding="utf-8") if args.out.exists() else ""
        )
        if current != text:
            print(f"{args.out} is out of date: run without --check")
            return 1
        return 0
    args.out.write_text(text, encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
